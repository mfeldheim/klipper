def get_zerog_logo_bitmap():
    """
    Returns a 128x64 bitmap array representing the custom ZeroG logo
    Converts the provided byte array to a 2D bitmap array
    1 = pixel on (black), 0 = pixel off (white/background)
    """
    bitmap = []

    # The provided data appears to be in row-major format
    # We need to determine the correct bytes per row
    # With 640 bytes total for 128x64, that's 10 bytes per row (80 pixels per row)
    # But we need 128 pixels per row, so let's assume it's 16 bytes per row for 40 rows

    # Actually, let's try a different approach - assume it's 16 bytes per row
    bytes_per_row = 16
    total_rows = len(CUSTOM_LOGO_DATA) // bytes_per_row

    # Create 64 rows, padding with zeros if needed
    for row in range(64):
        bitmap_row = []
        for col in range(128):
            if row < total_rows:
                byte_index = row * bytes_per_row + col // 8
                bit_index = 7 - (col % 8)  # MSB first

                if byte_index < len(CUSTOM_LOGO_DATA):
                    pixel = (CUSTOM_LOGO_DATA[byte_index] >> bit_index) & 1
                else:
                    pixel = 0
            else:
                pixel = 0

            bitmap_row.append(pixel)
        bitmap.append(bitmap_row)

    return bitmap

def bitmap_to_st7920_format(bitmap):
    """
    Convert bitmap to ST7920 graphics framebuffer format
    ST7920 uses 32 framebuffers of 32 bytes each
    Each byte represents 8 vertical pixels
    """
    framebuffers = []
    
    for fb_row in range(32):  # 32 framebuffers (rows)
        framebuffer = []
        for fb_col in range(32):  # 32 bytes per framebuffer (columns)
            byte_val = 0
            # Each byte represents 8 vertical pixels
            for bit in range(8):
                pixel_row = fb_row + (bit * 32)
                pixel_col = fb_col
                
                # Check bounds and get pixel value
                if pixel_row < 64 and pixel_col < 128:
                    if bitmap[pixel_row][pixel_col]:
                        byte_val |= (1 << bit)
                        
            framebuffer.append(byte_val)
        framebuffers.append(framebuffer)
    
    return framebuffers

